    private void inicializarTabla() {
        modeloTabla = new DefaultTableModel(
            new Object[][] {},
            new String[] {"ID", "CURP", "Nombre", "Apellido", "Dirección", "Municipio"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Evita que el usuario edite las celdas directamente en la tabla
            }
        };
        tblBeneficiarios.setModel(modeloTabla);
    }

    private void listarBeneficiarios() {
        modeloTabla.setRowCount(0); // Limpiar filas previas
        List<Beneficiario> lista = dao.listar();
        for (Beneficiario b : lista) {
            modeloTabla.addRow(new Object[]{
                b.getIdBeneficiario(),
                b.getCurp(),
                b.getNombre(),
                b.getApellido(),
                b.getDirection(),
                b.getMunicipio()
            });
        }
    }

