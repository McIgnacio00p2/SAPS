    private void jButtonGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonGuardarActionPerformed
        if (txtCurp.getText().isEmpty() || txtNombre.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "CURP y Nombre son obligatorios.");
            return;
        }

        Beneficiario b = new Beneficiario();
        b.setCurp(txtCurp.getText().trim());
        b.setNombre(txtNombre.getText().trim());
        b.setApellido(txtApellido.getText().trim());
        b.setDireccion(txtDireccion.getText().trim());
        b.setMunicipio(txtMunicipio.getText().trim());

        if (txtId.getText().isEmpty()) {
            // Ejecuta INSERT
            if (dao.insertar(b)) {
                JOptionPane.showMessageDialog(this, "Beneficiario registrado con éxito.");
                limpiarCampos();
                listarBeneficiarios();
            } else {
                JOptionPane.showMessageDialog(this, "Error al registrar. Verifica la CURP.");
            }
        } else {
            // Ejecuta UPDATE
            b.setIdBeneficiario(Integer.parseInt(txtId.getText()));
            if (dao.modificar(b)) {
                JOptionPane.showMessageDialog(this, "Datos actualizados correctamente.");
                limpiarCampos();
                listarBeneficiarios();
            } else {
                JOptionPane.showMessageDialog(this, "Error al actualizar los datos.");
            }
        }
    }//GEN-LAST:event_jButtonGuardarActionPerformed

    private void jButtonActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonActualizarActionPerformed
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione un beneficiario de la tabla para modificar.");
            return;
        }

        if (txtCurp.getText().isEmpty() || txtNombre.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "La CURP y el Nombre son campos obligatorios.");
            return;
        }

        Beneficiario b = new Beneficiario();
        b.setIdBeneficiario(Integer.parseInt(txtId.getText()));
        b.setCurp(txtCurp.getText().trim());
        b.setNombre(txtNombre.getText().trim());
        b.setApellido(txtApellido.getText().trim());
        b.setDireccion(txtDireccion.getText().trim());
        b.setMunicipio(txtMunicipio.getText().trim());

        if (dao.modificar(b)) {
            JOptionPane.showMessageDialog(this, "Registro actualizado correctamente en el sistema.");
            limpiarCampos();
            listarBeneficiarios();
        } else {
            JOptionPane.showMessageDialog(this, "Error en el servidor: No se pudieron actualizar los datos.");
        }
    }//GEN-LAST:event_jButtonActualizarActionPerformed

    private void jButtonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEliminarActionPerformed
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Selecciona un beneficiario de la tabla para eliminar.");
            return;
        }

        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Seguro que deseas eliminar este beneficiario?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (confirmacion == JOptionPane.YES_OPTION) {
            int id = Integer.parseInt(txtId.getText());
            if (dao.eliminar(id)) {
                JOptionPane.showMessageDialog(this, "Registro eliminado del sistema.");
                limpiarCampos();
                listarBeneficiarios();
            } else {
                JOptionPane.showMessageDialog(this, "Error del Administrador: No se puede eliminar (Restricción de Integridad).");
            }
        }
    }//GEN-LAST:event_jButtonEliminarActionPerformed

